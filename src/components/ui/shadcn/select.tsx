import * as React from "react"
import * as SelectPrimitive from "@radix-ui/react-select"
import { Check, ChevronDown, ChevronUp } from "lucide-react"

import { cn } from "@/components/ui/shadcn/utils"

const Select = SelectPrimitive.Root

const SelectGroup = SelectPrimitive.Group

const SelectValue = SelectPrimitive.Value

// The trigger looks like the app's .select: 36px, 10px radius, control border, ring + halo on focus.
const SelectTrigger = React.forwardRef<
  React.ElementRef<typeof SelectPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Trigger>
>(({ className, children, ...props }, ref) => (
  <SelectPrimitive.Trigger
    ref={ref}
    className={cn(
      "flex h-9 w-full items-center justify-between gap-2 whitespace-nowrap rounded-md border border-line-2 bg-surface px-3 text-left text-body text-ink transition-[border-color,box-shadow] duration-120 hover:border-line-3 focus:border-ring focus:shadow-focus focus:outline-none data-[placeholder]:text-muted disabled:cursor-not-allowed disabled:border-line disabled:bg-surface-2 disabled:text-faint dark:bg-surface-2 dark:focus:shadow-[0_0_0_3px_rgb(var(--ring)/.28)] max-sm:h-11 max-sm:text-[16px] [&>span]:line-clamp-1",
      className
    )}
    {...props}
  >
    {children}
    <SelectPrimitive.Icon asChild>
      <ChevronDown className="h-4 w-4 shrink-0 text-muted" />
    </SelectPrimitive.Icon>
  </SelectPrimitive.Trigger>
))
SelectTrigger.displayName = SelectPrimitive.Trigger.displayName

